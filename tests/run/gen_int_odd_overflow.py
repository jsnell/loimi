#!/usr/bin/env python3
# Generates tests/run/int_odd_overflow.lm (and, with `OUT --release`,
# int_odd_overflow_release.lm): checked/wrapping arithmetic,
# compares, division and shifts on iN/uN at their boundaries, against
# values computed in i64 (each width's expected results are computed by
# the program itself, so the expected output is just "ok" lines).
import sys
release = len(sys.argv) > 2 and sys.argv[2] == "--release"
WIDTHS = [3, 17, 31, 47, 48, 63] if release else [1, 2, 3, 5, 7, 9, 12, 15, 17, 23, 24, 31, 33, 40, 47, 48, 49, 53, 56, 62, 63]

def vals(n, signed):
    if signed:
        lo, hi = -(1 << (n - 1)), (1 << (n - 1)) - 1
        c = {lo, lo + 1, lo // 2, -2, -1, 0, 1, 2, hi // 2, hi // 2 + 1, hi - 1, hi,
             (1 << (n // 2)), -(1 << (n // 2)), (1 << ((n - 1) // 2)) - 1}
    else:
        lo, hi = 0, (1 << n) - 1
        c = {0, 1, 2, 3, hi // 2, hi // 2 + 1, hi - 1, hi, (1 << (n // 2)), (1 << ((n + 1) // 2)) - 1}
    return sorted(v for v in c if lo <= v <= hi)

out = []
w = out.append
w("// Generated by tests/run/gen_int_odd_overflow.py" + (" --release (optimized build, fewer widths)" if release else "") + ": odd-width integer")
w("// arithmetic at the boundaries of each width, against i64 references.")
w("// Operands pass through `z` (0 at run time) so nothing is constant-folded.")
w("import std.io;")
w("import std.os;")
w("")
w("fn p(s: str) { io.println(s); }")
w("fn bad(w: str, what: str, a: i64, b: i64) { io.print(w); io.print(\" \"); io.print(what); io.print(\" \"); io.print_int(a); io.print(\" \"); io.print_int(b); io.println(\"\"); }")
w("")
names = []
for n in WIDTHS:
    for signed in (True, False):
        if n == 1 and not signed:
            pass
        t = ("i" if signed else "u") + str(n)
        names.append(t)
        vs = vals(n, signed)
        lo, hi = (-(1 << (n - 1)), (1 << (n - 1)) - 1) if signed else (0, (1 << n) - 1)
        mask = (1 << n) - 1
        w(f"#[inline(never)]")
        w(f"fn check_{t}(z: i64) -> i64 {{")
        w(f"    var vs: [i64; {len(vs)}] = [{', '.join(str(v) for v in vs)}];")
        w(f"    let lo: i64 = {lo};")
        w(f"    let hi: i64 = {hi};")
        w(f"    var fails: i64 = 0;")
        w(f"    for i in 0..{len(vs)} {{")
        w(f"        for j in 0..{len(vs)} {{")
        w(f"            let a64 = vs[i] + z;")
        w(f"            let b64 = vs[j] + z;")
        w(f"            let a = a64 as {t};")
        w(f"            let b = b64 as {t};")
        # wrap an i64 to the width, as i64
        if signed:
            wrap = lambda e: f"((({e}) << {64 - n}) >> {64 - n})" if n < 64 else e
        else:
            wrap = lambda e: f"(({e}) & {mask})"
        for op, sym, ck in (("add", "+", "add_checked"), ("sub", "-", "sub_checked"), ("mul", "*", "mul_checked")):
            # exact result in i64 (operands are below 2^63 in magnitude for add/sub;
            # mul may overflow i64 itself: then it overflows the width too)
            w(f"            match a64.{ck}(b64) {{")
            w(f"                Some(r) => {{")
            w(f"                    let fits = r >= lo and r <= hi;")
            w(f"                    match a.{ck}(b) {{")
            w(f"                        Some(x) => if !fits or x as i64 != r {{ bad(\"{t}\", \"{op}\", a64, b64); fails += 1; }},")
            w(f"                        None => if fits {{ bad(\"{t}\", \"{op} none\", a64, b64); fails += 1; }},")
            w(f"                    }}")
            w(f"                }}")
            w(f"                None => if a.{ck}(b).is_some() {{ bad(\"{t}\", \"{op} some\", a64, b64); fails += 1; }},")
            w(f"            }}")
            w(f"            if (a {sym}% b) as i64 != {wrap(f'a64 {sym}% b64')} {{ bad(\"{t}\", \"{op} wrap\", a64, b64); fails += 1; }}")
        # compares
        w(f"            if (a < b) != (a64 < b64) or (a <= b) != (a64 <= b64) or (a == b) != (a64 == b64) or (a > b) != (a64 > b64) {{ bad(\"{t}\", \"cmp\", a64, b64); fails += 1; }}")
        # division and remainder (no zero divisor, no MIN / -1)
        cond = "b64 != 0" + (f" and !(a64 == lo and b64 == -1)" if signed else "")
        w(f"            if {cond} {{")
        w(f"                if (a / b) as i64 != a64 / b64 or (a % b) as i64 != a64 % b64 {{ bad(\"{t}\", \"div\", a64, b64); fails += 1; }}")
        w(f"                if b > ({0 if not signed else 0} as {t}) and (a / b) as i64 != a64 / b64 {{ bad(\"{t}\", \"div pos\", a64, b64); fails += 1; }}")
        w(f"            }}")
        # shifts: by b mod n
        w(f"            let s = (b64 as u64 % {n}) as {t};")
        w(f"            let s64 = (b64 as u64 % {n}) as i64;")
        w(f"            if (a << s) as i64 != {wrap('a64 << s64')} {{ bad(\"{t}\", \"shl\", a64, b64); fails += 1; }}")
        w(f"            if (a >> s) as i64 != a64 >> s64 {{ bad(\"{t}\", \"shr\", a64, b64); fails += 1; }}")
        w(f"        }}")
        # negation, casts
        w(f"        let a64 = vs[i] + z;")
        w(f"        let a = a64 as {t};")
        w(f"        if ((0 as {t}) -% a) as i64 != {wrap('0 -% a64')} {{ bad(\"{t}\", \"neg\", a64, 0); fails += 1; }}")
        w(f"        match (0 as {t}).sub_checked(a) {{")
        w(f"            Some(x) => if 0 - a64 < lo or 0 - a64 > hi or x as i64 != 0 - a64 {{ bad(\"{t}\", \"neg checked\", a64, 0); fails += 1; }},")
        w(f"            None => if 0 - a64 >= lo and 0 - a64 <= hi {{ bad(\"{t}\", \"neg none\", a64, 0); fails += 1; }},")
        w(f"        }}")
        w(f"        if (a as f64) != (a64 as f64) {{ bad(\"{t}\", \"to f64\", a64, 0); fails += 1; }}")
        w(f"    }}")
        w(f"    fails")
        w(f"}}")
        w("")
w("fn main() {")
w("    let z = os.arg_count() as i64 - 1;")
w("    var fails: i64 = 0;")
for t in names:
    w(f"    fails += check_{t}(z);")
w("    if fails == 0 { p(\"ok\"); } else { io.print_int(fails); p(\" failures\"); }")
w("}")
w("")
w("// expect: ok")
if release:
    w("// args: --release")
open(sys.argv[1], "w").write("\n".join(out) + "\n")
