# Float floor division/modulo, divmod, pow with a modulus, round with negative digits, operand-type errors.

def run(e, e2):
    try:
        print(e, repr(e2()))
    except Exception as x:
        print(e, type(x).__name__, x)

run('divmod(1.0, 0)', lambda: divmod(1.0, 0))
run('divmod(1, 0)', lambda: divmod(1, 0))
run('divmod(1.5, "a")', lambda: divmod(1.5, "a"))
run('pow(2, 3, 0)', lambda: pow(2, 3, 0))
