% Unification, comparison, term inspection and construction, standard
% order, sorting, copy_term.

main :-
    ( f(X, b) = f(a, Y) -> write(X-Y) ; write(no) ), nl,
    ( f(a) = g(a) -> write(yes) ; write(no) ), nl,
    ( [1, 2|T] = [A, B, 3] -> write([A, B, T]) ; write(no) ), nl,
    ( g(Z, Z) = g(1, 2) -> write(yes) ; write(no) ), nl,
    ( g(Z1, Z1) = g(W, 2) -> write(W) ; write(no) ), nl,
    ( a \= b -> write(ne) ; write(eq) ), nl,
    ( f(_) \= f(1) -> write(ne) ; write(unifiable) ), nl,
    ( f(a) == f(a) -> write(same) ; write(diff) ), nl,
    ( f(_) == f(_) -> write(same) ; write(diff) ), nl,
    ( 1 == 1.0 -> write(same) ; write(diff) ), nl,
    ( 1 =:= 1.0 -> write(numeq) ; write(numne) ), nl,
    compare(O1, 1, a), compare(O2, f(a), a), compare(O3, f(b), g(a)),
    compare(O4, f(a, b), g(a)), compare(O5, 1.0, 1), compare(O6, 2, 1.5),
    write([O1, O2, O3, O4, O5, O6]), nl,
    msort([c, 1, f(x), b, 2.0, a, g(a, b), [1], Q], L1), Q = var,
    write(L1), nl,
    sort([c, a, b, a, c], L2), write(L2), nl,
    sort(0, @>=, [1, 3, 2, 3], L3), write(L3), nl,
    keysort([b-1, a-2, b-0, a-1], L4), write(L4), nl,
    functor(foo(a, b, c), N, Ar), write(N/Ar), nl,
    functor(T2, bar, 2), T2 =.. [_|BA], length(BA, NBA), write(NBA), nl,
    functor(T3, baz, 0), write(T3), nl,
    functor([a], N2, A2), write(N2/A2), nl,
    arg(2, foo(a, b, c), Arg), write(Arg), nl,
    F =.. [point, 1, 2], write(F), nl,
    point(1, 2) =.. L5, write(L5), nl,
    [a, b] =.. L6, write(L6), nl,
    abc =.. L7, write(L7), nl,
    copy_term(f(X9, Y9, X9), C), C = f(1, 2, Z9), write(Z9), nl,
    ( var(X9) -> write(orig_unbound) ; write(orig_bound) ), nl,
    term_variables(f(V1, g(V2, V1), _), Vs), length(Vs, NV), write(NV), nl,
    ( ground(f(a, [b])) -> write(ground) ; write(nonground) ), nl,
    ( ground(f(a, [_])) -> write(ground) ; write(nonground) ), nl,
    ( atom(abc), atomic(1), number(1.5), integer(3), float(3.0), compound(f(x)),
      callable(foo), callable(f(1)), \+ callable(3), is_list([1,2]), \+ is_list([1|_]),
      var(_), nonvar(a) -> write(types_ok) ; write(types_bad) ), nl,
    length(LL, 3), LL = [p|_], last(LL, q), msort(LL, SL), length(SL, SN), write(SN), nl,
    length([a, b, c, d], Len), write(Len), nl,
    ( length([a|_], 1) -> write(partial_ok) ; write(partial_no) ), nl.
:- initialization(main).
